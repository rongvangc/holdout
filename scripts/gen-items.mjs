// Turn tools/innawoods-catalog.json into src/data/items.generated.ts.
//
//   node scripts/gen-items.mjs
//
// The catalog is a draft: kg, mitigation, durability and kcal came from
// scripts/mine-innawoods.mjs heuristics. Tune values in the catalog, re-run this.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const CATALOG = path.resolve('tools', 'innawoods-catalog.json');
const OUT = path.resolve('src', 'data', 'items.generated.ts');

const PREFIX = {
  weapon_blade: 'wpn',
  weapon_blunt: 'blnt',
  firearm: 'gun',
  ammo: 'ammo',
  armor_soft: 'arm',
  armor_plate: 'plate',
  helmet: 'helm',
  mask: 'mask',
  clothes: 'cloth',
  backpack: 'pack',
  container: 'bag',
  gloves: 'glove',
  boots: 'boot',
  vest: 'vest',
  food: 'food',
  drink: 'drink',
  comfort: 'comfort',
  medicine: 'med',
  bandage: 'band',
  injection: 'inj',
  hygiene: 'hyg',
  medkit: 'kit',
  tool: 'tool',
  fire: 'fire',
  cookware: 'cook',
  camping: 'camp',
  electronic: 'elec',
  misc: 'misc',
};

const CATEGORY = {
  weapon_blade: 'weapon',
  weapon_blunt: 'weapon',
  firearm: 'weapon',
  ammo: 'ammo',
  armor_soft: 'armor',
  armor_plate: 'armor',
  helmet: 'armor',
  mask: 'armor',
  vest: 'armor',
  clothes: 'clothing',
  gloves: 'clothing',
  boots: 'clothing',
  backpack: 'container',
  container: 'container',
  food: 'food',
  drink: 'drink',
  comfort: 'comfort',
  medicine: 'medicine',
  bandage: 'medicine',
  injection: 'medicine',
  hygiene: 'medicine',
  medkit: 'medicine',
  tool: 'tool',
  fire: 'tool',
  cookware: 'cookware',
  camping: 'camping',
  electronic: 'electronic',
  misc: 'misc',
};

const UNIT = {
  ammo: 'viên',
  food: 'phần',
  drink: 'phần',
  medicine: 'liều',
  bandage: 'cuộn',
  injection: 'mũi',
  medkit: 'bộ',
  comfort: 'gói',
};

const slug = (s) =>
  s
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase()
    .slice(0, 40);

const q = (v) => JSON.stringify(v);

const catalog = JSON.parse(await readFile(CATALOG, 'utf8'));
const used = new Set();
const lines = [];

for (const it of catalog.items) {
  const prefix = PREFIX[it.mechanic] ?? 'item';
  let id = `${prefix}_${slug(it.name)}` || `${prefix}_x`;
  if (used.has(id)) {
    let n = 2;
    while (used.has(`${id}-${n}`)) n++;
    id = `${id}-${n}`;
  }
  used.add(id);

  const fields = [
    `label: ${q(it.name)}`,
    `unit: ${q(UNIT[it.mechanic] ?? 'cái')}`,
    `kgPerUnit: ${it.kg}`,
    `category: ${q(CATEGORY[it.mechanic] ?? 'misc')}`,
    `mechanic: ${q(it.mechanic)}`,
    `tier: ${it.tier}`,
  ];
  if (it.icon) fields.push(`icon: ${q('/' + it.icon.replace(/^\/+/, ''))}`);
  if (it.mitigation !== undefined) fields.push(`mitigation: ${it.mitigation}`);
  if (it.durability !== undefined) fields.push(`durability: ${it.durability}`);
  if (it.biteMult !== undefined) fields.push(`biteMult: ${it.biteMult}`);
  if (it.cls) fields.push(`cls: ${q(it.cls)}`);
  if (it.noise !== undefined) fields.push(`noise: ${it.noise}`);
  if (it.rare) fields.push('rare: true');
  if (it.caliber) fields.push(`caliber: ${q(it.caliber)}`);
  if (it.kcal !== undefined) fields.push(`kcal: ${it.kcal}`);
  if (it.rotPerDay !== undefined) fields.push(`rotPerDay: ${it.rotPerDay}`);
  if (it.capacity !== undefined) fields.push(`capacity: ${it.capacity}`);
  if (it.power) fields.push(`power: ${q(it.power)}`);
  if (it.heal) fields.push(`heal: ${it.heal}`);
  if (it.cures) fields.push('cures: true');
  if (it.subtype) fields.push(`subtype: ${q(it.subtype)}`);

  lines.push(`  ${q(id)}: { ${fields.join(', ')} },`);
}

const out = `// GENERATED by scripts/gen-items.mjs from tools/innawoods-catalog.json — do not edit.
// ${catalog.items.length} items. Recipes live in src/data/recipes.ts.
import type { ItemDef } from './items';

export const GENERATED_ITEMS: Record<string, ItemDef> = {
${lines.join('\n')}
};
`;

await writeFile(OUT, out);
console.log(`wrote ${catalog.items.length} items -> ${path.relative('.', OUT)}`);
